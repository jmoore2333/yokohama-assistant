#!/usr/bin/env python3
"""Regenerate the README's terminal animation from a recorded game.

The animation is `docs/images/cli-game.gif`, eleven frames of the terminal
client through one game against the bot that ships. This replaces the scratch
scripts the 2026-11-09 animation was cut with (issue #69), and keeps their
recipe: the CLI under a pseudo-terminal, its cells laid out as HTML, drawn by
headless Chromium.

    python3 docs/tools/mkcligif.py --record <game.json> --scratch <dir>            # writes docs/images/cli-game.gif
    python3 docs/tools/mkcligif.py --record <game.json> --scratch <dir> --check    # compare, write nothing (exit 1 on drift)

Run from anywhere; build the CLI first (`cargo build --release -p yokohama-cli`).
The inputs are named on the command line:

  --record   the finished game the animation walks through. The committed
             animation is cut from the owner's game 4 record, held outside the
             tree (a full game against the shipped bot, Red 82 - Blue 81).
  --cli      the terminal client's binary (default: target/release/yokohama-cli).
  --out      the animation (default: docs/images/cli-game.gif).
  --scratch  a directory for the copies the CLI resumes, the raw captures, the
             HTML pages and the PNG per frame. Nothing in it is committed.

WHAT A FRAME IS. Every frame is the real output of the built CLI at a real
position of the record, and nothing else. For each frame the tool writes a copy
of the record into the scratch directory whose events are a PREFIX of the
record's (the first k), with `terminal_digest` cleared (it is the digest of the
finished game and a prefix has none) and `engine_version` set to the running
build's, so the CLI does not print its version-mismatch warning in frame -- the
recipe of the 2026-11-09 animation, which shows no such notice either. It
resumes that copy under a pseudo-terminal of 200 x 62 cells (the CLI's floor is
200 x 50; 62 rows hold `why`'s table whole), types what the frame's row in
FRAMES says, if anything, waits for the CLI to settle and reads the screen. The
CLI autosaves into the file it resumes, which is why it only ever gets the
scratch copy. Where the CLI plays the bot (a copy that stops with Blue to move),
the tool also checks that the bot's moves, read back from the autosave, are the
record's own: a frame that showed a different game would fail there.

READING THE SCREEN. The tool keeps a small screen model of its own (no
terminal library is needed): printable characters at the cursor, carriage
return, line feed with scrolling into a scrollback, erase-display, cursor home,
erase-to-end-of-line, and the SGR attributes the CLI uses (bold, dim, reverse,
the 16 and four 256-colour foregrounds). Any other control sequence STOPS the
run, naming it, rather than drawing a guess. A frame is the 62 rows on screen,
except where FRAMES names a marker: then the window is scrolled back to start at
the last row that carries it (`why`'s output is a page taller than the prompt's
screen, and its header is the frame's point) -- the terminal's own rows, read as
a reader would scroll to them.

DRAWING. Each frame becomes an HTML page with one fixed-width cell per
character (13px Menlo, line height 1.32, the GitHub-dark palette below), drawn
by Chromium's headless shell at 1618 x 1108 -- 200 cells and 62 rows plus the
padding -- and Pillow assembles the GIF at the durations in FRAMES, looping
forever. Chromium's headless shell is found under Playwright's cache
(`~/Library/Caches/ms-playwright` or `~/.cache/ms-playwright`), or named with
`--chrome`.

--check runs the capture again and compares each frame's TEXT -- the cells'
characters, colours aside -- with `docs/images/cli-game.frames.txt`, the text the
committed animation was cut from, written beside it on every regeneration. It
writes no picture. A drift there means the terminal now draws a frame
differently (a deliberate CLI change is the usual cause): regenerate, and read
the README's alt and caption against the new frames before committing.

WHAT THE FRAMES SHOW OF THE HIDDEN CARDS. Red's seat is the human's, so Red's
hand is in frame by design. The bot's hand is masked as the CLI masks it on the
dashboard (`Orders  1 in hand (hidden)`), and the tool stops if any `Orders` row
of Blue's block lacks that `(hidden)`. One frame carries something of it all the
same, by the CLI's design: `why` is the bot's own account of its move, so its
table of features is computed from the bot's view, its own hand included
(`held_order_value`, `order_matched_goods`); the 2026-11-09 animation showed the
same table for the same move.

The tool prints, per frame, the event index the copy stops at and the
keystrokes typed, so one frame can be regenerated by hand:
`<cli> <copy-of-the-first-k-events.json>`, then type the keys.

REQUIREMENTS: Python 3.11+ (`tomllib`), Pillow, and a Chromium headless shell.
Nothing in the workspace's Rust build or test path runs this.
"""

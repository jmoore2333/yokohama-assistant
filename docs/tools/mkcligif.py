ROOT = pathlib.Path(__file__).resolve().parents[2]
ROWS, COLS = 62, 200
WIDTH, HEIGHT = 1618, 1108          # 200 cells of 13px Menlo + 2 x 26px, 62 x 1.32 x 13px + 2 x 22px
TEXT_SIDECAR = ROOT / "docs" / "images" / "cli-game.frames.txt"

PROMPT = r"(?m)^> ?$"   # the CLI's prompt, alone on its row

# The storyboard (the README's alt, in order). `k` is the number of the record's
# events the copy keeps, `keys` what is typed once the CLI has settled, `wait`
# a pattern the CLI must print (after the keys, if any) before the frame is read, `scroll` the marker
# the window is scrolled back to, `ms` the frame's duration.
#   - k=0: the opening screen, Red to decide.
#   - k=7: the record stops with Blue to move, so the CLI plays the bot's whole
#     turn (events 7-16) and shows its pause screen, move by move.
#   - k=17, `why 8`: the bot's own account of event 8, its first placement.
#   - seven later turns of Red's, read at the turn's start, except turn 9, read
#     at its Area Action (k=63, the President in the Church): the main list's
#     one Church entry that opens the chooser, where the terminal used to list
#     every legal payment.
#   - k=247: the finished game; `score` opens the final breakdown.
FRAMES = [
    {"k": 0, "keys": "", "wait": PROMPT, "ms": 2800},
    {"k": 7, "keys": "", "wait": r"This screen is a pause", "ms": 4000},
    {"k": 17, "keys": "why 8", "wait": r"rows carry a nonzero product", "scroll": "─ Why", "ms": 5000},
    {"k": 31, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 63, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 91, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 122, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 152, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 184, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 213, "keys": "", "wait": PROMPT, "ms": 1300},
    {"k": 247, "keys": "score", "wait": r"─ Final scores", "ms": 6000},
]

# The palette (GitHub dark), keyed by the SGR foregrounds the CLI emits.
FG, BG = "#c9d1d9", "#0d1117"
BASE = {31: "#ff7b72", 32: "#3fb950", 33: "#d29922", 34: "#79c0ff", 35: "#d2a8ff", 36: "#56d4dd", 37: "#c9d1d9",
        90: "#7d8590", 91: "#ff7b72", 92: "#56d364", 93: "#e3b341", 94: "#79c0ff", 95: "#d2a8ff", 96: "#56d4dd",
        97: "#ffffff"}
XTERM = {75: "#5fafff", 172: "#d78700", 178: "#d7af00", 220: "#ffd700"}

SETTLE = 1.0      # seconds of silence after the wait pattern shows before the screen is read
TIMEOUT = 180.0   # the longest any one step may take (the bot's turn is the slow one)


# --------------------------------------------------------------------------- the screen model

class Screen:
    """The cells of a ROWS x COLS terminal and the rows scrolled off its top."""

    def __init__(self) -> None:
        self.blank = (" ", None, False, False, False)
        self.rows = [[self.blank] * COLS for _ in range(ROWS)]
        self.history: list[list] = []
        self.r = self.c = 0
        self.wrap = False                     # xterm's deferred wrap: the cursor sits past the last column
        self.attr = {"fg": None, "bold": False, "dim": False, "rev": False}
        self.pending = ""

    def feed(self, data: str) -> None:
        s = self.pending + data
        self.pending = ""
        i = 0
        while i < len(s):
            ch = s[i]
            if ch == "\x1b":
                m = re.compile(r"\x1b\[([?0-9;]*)([@-~])").match(s, i)
                if not m:
                    if len(s) - i < 32 and re.fullmatch(r"\x1b(\[[?0-9;]*)?", s[i:]):
                        self.pending = s[i:]     # a sequence split across two reads
                        return
                    raise SystemExit(f"unhandled escape {s[i:i + 12]!r}")
                self.csi(m.group(1), m.group(2))
                i = m.end()
                continue
            if ch == "\r":
                self.c, self.wrap = 0, False
            elif ch == "\n":
                self.linefeed()
            elif ch in "\x07":
                pass
            elif ord(ch) < 0x20 or ch == "\x7f":
                raise SystemExit(f"unhandled control character {ch!r}")
            else:
                if self.wrap:
                    self.c, self.wrap = 0, False
                    self.linefeed()
                a = self.attr
                self.rows[self.r][self.c] = (ch, a["fg"], a["bold"], a["dim"], a["rev"])
                if self.c == COLS - 1:
                    self.wrap = True
                else:
                    self.c += 1
            i += 1

    def linefeed(self) -> None:
        self.wrap = False
        if self.r == ROWS - 1:
            self.history.append(self.rows.pop(0))
            self.rows.append([self.blank] * COLS)
        else:
            self.r += 1

    def csi(self, params: str, final: str) -> None:
        if params.startswith("?") and final in "hl":
            return                                    # bracketed paste, synchronized output: no cells
        ps = [int(x) for x in params.split(";") if x != ""] if params else []
        if final == "m":
            self.sgr(ps or [0])
        elif final == "H" and not ps:
            self.r = self.c = 0
            self.wrap = False
        elif final == "J" and ps == [2]:
            self.rows = [[self.blank] * COLS for _ in range(ROWS)]
        elif final == "K" and not ps:
            self.rows[self.r][self.c:] = [self.blank] * (COLS - self.c)
        else:
            raise SystemExit(f"unhandled control sequence ESC[{params}{final}")

    def sgr(self, ps: list[int]) -> None:
        a, i = self.attr, 0
        while i < len(ps):
            p = ps[i]
            if p == 0:
                a.update(fg=None, bold=False, dim=False, rev=False)
            elif p == 1:
                a["bold"] = True
            elif p == 2:
                a["dim"] = True
            elif p == 22:
                a.update(bold=False, dim=False)
            elif p == 7:
                a["rev"] = True
            elif p == 27:
                a["rev"] = False
            elif p == 39:
                a["fg"] = None
            elif p == 38 and i + 2 < len(ps) and ps[i + 1] == 5:
                if ps[i + 2] not in XTERM:
                    raise SystemExit(f"unmapped 256-colour {ps[i + 2]}")
                a["fg"] = XTERM[ps[i + 2]]
                i += 2
            elif p in BASE:
                a["fg"] = BASE[p]
            else:
                raise SystemExit(f"unhandled SGR {p} in {ps}")
            i += 1

    def text(self, row: list) -> str:
        return "".join(cell[0] for cell in row).rstrip()

    def window(self, marker: str | None) -> list[list]:
        """The frame's 62 rows: the screen, or scrolled back to the last row carrying `marker`."""
        if marker is None:
            return [list(r) for r in self.rows]
        every = self.history + self.rows
        hits = [i for i, row in enumerate(every) if marker in self.text(row)]
        if not hits:
            raise SystemExit(f"no row carries {marker!r}")
        out = every[hits[-1]:hits[-1] + ROWS]
        return [list(r) for r in out] + [[self.blank] * COLS for _ in range(ROWS - len(out))]


# --------------------------------------------------------------------------- one capture

def build_version() -> str:
    return tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]["package"]["version"]


def prefix_copy(record: dict, k: int, path: pathlib.Path, version: str) -> None:
    d = json.loads(json.dumps(record))
    if k < len(d["events"]):
        d["events"] = d["events"][:k]
        d["terminal_digest"] = None
    d["engine_version"] = version
    path.write_text(json.dumps(d))


def capture(cli: pathlib.Path, save: pathlib.Path, frame: dict) -> tuple[Screen, bytes]:
    """Resume `save` under a 62 x 200 pseudo-terminal, type the frame's keys, return the settled screen."""
    pid, fd = pty.fork()
    if pid == 0:  # the child: the CLI, on the pseudo-terminal
        fcntl.ioctl(0, termios.TIOCSWINSZ, struct.pack("HHHH", ROWS, COLS, 0, 0))
        env = {k: v for k, v in os.environ.items() if k != "NO_COLOR"}
        env.update(TERM="xterm-256color", COLUMNS=str(COLS), LINES=str(ROWS))
        os.chdir(save.parent)
        os.execve(str(cli), [str(cli), str(save)], env)
    fcntl.ioctl(fd, termios.TIOCSWINSZ, struct.pack("HHHH", ROWS, COLS, 0, 0))
    screen, raw = Screen(), bytearray()

    def pump_until(pattern: str) -> None:
        """Read until the CLI has printed `pattern` in THIS step's output and then fallen quiet."""
        deadline = time.time() + TIMEOUT
        seen, fresh = False, ""
        quiet_since = time.time()
        decoder_buf = b""
        while True:
            r, _, _ = select.select([fd], [], [], 0.1)
            if r:
                try:
                    chunk = os.read(fd, 65536)
                except OSError:
                    chunk = b""
                if not chunk:
                    raise SystemExit(f"the CLI exited before the frame settled; it printed:\n{raw.decode('utf-8', 'replace')[-2000:]}")
                raw.extend(chunk)
                decoder_buf += chunk
                try:
                    text = decoder_buf.decode("utf-8")
                    decoder_buf = b""
                except UnicodeDecodeError:
                    continue                     # a character split across two reads
                screen.feed(text)
                fresh += text
                quiet_since = time.time()
            if not seen:
                plain = re.sub(r"\x1b\[[?0-9;]*[@-~]", "", fresh).replace("\r", "")
                seen = re.search(pattern, plain) is not None
            if seen and time.time() - quiet_since >= SETTLE:
                return
            if time.time() > deadline:
                raise SystemExit(f"timed out waiting for {pattern!r}; the screen reads:\n"
                                 + "\n".join(screen.text(r) for r in screen.rows))

    try:
        if frame["keys"]:
            pump_until(PROMPT)
            os.write(fd, frame["keys"].encode() + b"\r")
        pump_until(frame["wait"])
    finally:
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        os.waitpid(pid, 0)
        os.close(fd)
    return screen, bytes(raw)


# --------------------------------------------------------------------------- drawing

def page(rows: list[list]) -> str:
    def style(cell) -> str:
        _, fg, bold, dim, rev = cell
        css = []
        if rev:
            css += [f"color:{BG}", f"background:{fg or FG}"]
        elif fg:
            css.append(f"color:{fg}")
        if bold:
            css.append("font-weight:700")
        if dim:
            css.append("opacity:.62")
        return ";".join(css)

    body = []
    for row in rows:
        cells = []
        for cell in row:
            st = style(cell)
            ch = html.escape(cell[0])
            cells.append(f'<i style="{st}">{ch}</i>' if st else f"<i>{ch}</i>")
        body.append("<div>" + "".join(cells) + "</div>")
    return f"""<!doctype html><meta charset="utf-8"><style>
html,body{{margin:0;background:{BG};overflow:hidden}}
#term{{box-sizing:content-box;width:{COLS}ch;height:calc({ROWS} * 1.32em);padding:22px 26px;background:{BG};color:{FG};
  font:13px/1.32 Menlo,"SF Mono",Monaco,monospace;white-space:pre;overflow:hidden}}
#term div{{height:1.32em}}
#term i{{display:inline-block;width:1ch;font-style:normal;text-align:center;overflow:visible}}
</style><div id="term">{"".join(body)}</div>"""


def find_chrome(named: str | None) -> pathlib.Path:
    if named:
        return pathlib.Path(named)
    for cache in ("~/Library/Caches/ms-playwright", "~/.cache/ms-playwright"):
        found = sorted(glob.glob(os.path.expanduser(cache) + "/chromium_headless_shell-*/chrome-headless-shell-*/chrome-headless-shell"),
                       key=lambda p: int(re.search(r"chromium_headless_shell-(\d+)", p).group(1)))
        if found:
            return pathlib.Path(found[-1])
    sys.exit("no Chromium headless shell found under Playwright's cache: name one with --chrome")


def shoot(chrome: pathlib.Path, html_path: pathlib.Path, png: pathlib.Path) -> None:
    subprocess.run([str(chrome), "--headless", "--hide-scrollbars", "--force-device-scale-factor=1",
                    f"--window-size={WIDTH},{HEIGHT}", f"--screenshot={png}", html_path.as_uri()],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=120)
    with Image.open(png) as im:
        if im.size != (WIDTH, HEIGHT):
            sys.exit(f"{png.name} is {im.size}, not {WIDTH} x {HEIGHT}")


# --------------------------------------------------------------------------- the animation

def assemble(images: list[Image.Image], out: pathlib.Path) -> list[Image.Image]:
    """Write the GIF: one palette for every frame, and each frame after the first
    carrying only the pixels that changed (the rest transparent, drawn over the
    frame before). Returns the frames as they should decode.

    WHY THIS ENCODING (measured on this storyboard, 2026-11-22). Chromium's
    anti-aliased text gives each frame about 2,000 colours. Pillow's default (a
    palette per frame) wrote 1,139,435 B, against the 641,466 B of the
    2026-11-09 animation, whose frames ImageMagick had cut to 41-126 colours.
    One median-cut palette of 256 for all frames: 852,195 B. One max-coverage
    palette of 127 colours, plus an index for "unchanged" so that a frame after
    the first stores only what differs from the one before: 678,573 B, with the
    coloured text still its own colour at 1:1 (max coverage keeps the colours that
    cover the most pixels, so it was checked by eye on the dashboard and the
    tracks, where the small coloured runs are)."""
    colors = 127
    w, h = images[0].size
    strip = Image.new("RGB", (w, h * len(images)))
    for i, im in enumerate(images):
        strip.paste(im, (0, h * i))
    pal = strip.quantize(colors=colors, method=Image.Quantize.MAXCOVERAGE, dither=Image.Dither.NONE)
    palette = pal.getpalette()[:3 * colors] + [0, 0, 0] * (256 - colors)
    quantized = [im.quantize(palette=pal, dither=Image.Dither.NONE) for im in images]
    unchanged = colors                                # the one index no colour uses
    written = []
    for i, frame in enumerate(quantized):
        f = frame.copy()
        f.putpalette(palette)
        if i:
            same = ImageChops.difference(Image.frombytes("L", f.size, frame.tobytes()),
                                         Image.frombytes("L", f.size, quantized[i - 1].tobytes()))
            hole = Image.new("P", f.size, unchanged)
            hole.putpalette(palette)
            f.paste(hole, (0, 0), same.point(lambda v: 255 if v == 0 else 0))
        written.append(f)
    written[0].save(out, save_all=True, append_images=written[1:], duration=[f["ms"] for f in FRAMES],
                    loop=0, transparency=unchanged, disposal=1, optimize=False)
    # Read it back: every frame must decode to exactly its quantized picture.
    with Image.open(out) as gif:
        if gif.n_frames != len(images):
            sys.exit(f"{out.name} decodes to {gif.n_frames} frames, not {len(images)}")
        for i in range(gif.n_frames):
            gif.seek(i)
            if ImageChops.difference(gif.convert("RGB"), quantized[i].convert("RGB")).getbbox():
                sys.exit(f"{out.name}'s frame {i} does not decode to the picture it was cut from")
            if gif.info.get("duration") != FRAMES[i]["ms"]:
                sys.exit(f"{out.name}'s frame {i} lasts {gif.info.get('duration')} ms, not {FRAMES[i]['ms']}")
    return quantized


# --------------------------------------------------------------------------- checks on a frame

def bot_hand_masked(rows: list[str]) -> None:
    """Every `Orders` row of Blue's dashboard block reads `(hidden)`; a frame that
    shows the dashboard and no such row is a reader that read nothing, and stops too."""
    in_blue, checked = False, 0
    for line in rows:
        right = line[120:] if len(line) > 120 else line
        if re.search(r"\bRED\b", right):
            in_blue = False
        if re.search(r"\bBLUE\b", right):
            in_blue = True
        m = re.search(r"Orders\s+(\d+) in hand(.*)", right)
        if m and in_blue:
            if "(hidden)" not in m.group(2):
                raise SystemExit(f"a frame shows the bot's hand unmasked: {right.strip()!r}")
            checked += 1
    if checked == 0 and any("─ PLAYERS" in line for line in rows):
        raise SystemExit("a frame shows the dashboard but no Orders row of Blue's was read")


def bot_moves_are_the_records(save: pathlib.Path, record: dict, k: int) -> int:
    after = json.loads(save.read_text())["events"]
    n = len(after)
    if after != record["events"][:n] or n <= k:
        raise SystemExit(f"the bot's turn from event {k} is not the record's: events {k}..{n - 1} differ")
    return n


# --------------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--record", required=True, help="the finished game's record (JSON)")
    ap.add_argument("--cli", default=str(ROOT / "target" / "release" / "yokohama-cli"), help="the CLI binary")
    ap.add_argument("--out", default=str(ROOT / "docs" / "images" / "cli-game.gif"), help="the animation to write")
    ap.add_argument("--scratch", required=True, help="a directory for the copies, captures and frames")
    ap.add_argument("--chrome", help="Chromium's headless shell (default: the newest under Playwright's cache)")
    ap.add_argument("--check", action="store_true",
                    help="compare each frame's text with the committed text, write no picture, exit 1 on drift")
    args = ap.parse_args()

    cli = pathlib.Path(args.cli).resolve()
    if not cli.is_file():
        sys.exit(f"no CLI at {cli}: cargo build --release -p yokohama-cli")
    scratch = pathlib.Path(args.scratch).resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    record = json.loads(pathlib.Path(args.record).read_text())
    version = build_version()
    chrome = None if args.check else find_chrome(args.chrome)

    texts, pngs = [], []
    for n, frame in enumerate(FRAMES):
        k = frame["k"]
        save = scratch / f"k{k:03d}.json"
        prefix_copy(record, k, save, version)
        screen, raw = capture(cli, save, frame)
        (scratch / f"f{n:02d}-k{k:03d}.raw").write_bytes(raw)
        rows = screen.window(frame.get("scroll"))
        lines = [screen.text(r) for r in rows]
        bot_hand_masked(lines)
        note = ""
        if k < len(record["events"]) and json.loads(save.read_text())["events"] != record["events"][:k]:
            upto = bot_moves_are_the_records(save, record, k)
            note = f"  (the CLI played the bot: events {k}-{upto - 1}, the record's own)"
        keys = f"type {frame['keys']!r} + Enter" if frame["keys"] else "type nothing"
        print(f"frame {n:2d}  event index {k:3d}  {cli} {save}  (the record's first {k} events), {keys}"
              + (f", scrolled to {frame['scroll']!r}" if frame.get("scroll") else "") + f"  {frame['ms']} ms{note}")
        texts.append(f"=== frame {n} · k={k} · keys={frame['keys']!r}\n" + "\n".join(lines).rstrip("\n") + "\n")
        if not args.check:
            page_path = scratch / f"f{n:02d}-k{k:03d}.html"
            page_path.write_text(page(rows), encoding="utf-8")
            png = scratch / f"f{n:02d}-k{k:03d}.png"
            shoot(chrome, page_path, png)
            pngs.append(png)

    text = "".join(texts)
    if args.check:
        committed = TEXT_SIDECAR.read_text(encoding="utf-8") if TEXT_SIDECAR.exists() else ""
        if committed == text:
            print(f"OK: every frame's text equals {TEXT_SIDECAR.relative_to(ROOT)}")
            return 0
        (scratch / "frames.now.txt").write_text(text, encoding="utf-8")
        got, want = text.split("=== "), committed.split("=== ")
        for i in range(max(len(got), len(want))):
            if i >= len(got) or i >= len(want) or got[i] != want[i]:
                print(f"DRIFTED: frame {i - 1}")
        print(f"the text now is in {scratch / 'frames.now.txt'}")
        return 1

    out = pathlib.Path(args.out)
    frames = assemble([Image.open(p).convert("RGB") for p in pngs], out)

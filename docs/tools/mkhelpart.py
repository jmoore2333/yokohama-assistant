#!/usr/bin/env python3
"""Re-cut the help panel's screenshots from PNG to WebP.

    python3 docs/tools/mkhelpart.py              # from the repo root
    python3 docs/tools/mkhelpart.py --check      # compare, write nothing (exit 1 on drift)

Reads `web/help-shots/*.png` and writes one WebP per picture, at the same base
name, into `web/public/help/`. **It never reads or writes the sprite sheets,
which are not in the tree**: the input is this repository's own application, photographed.

WHERE THE PNGs COME FROM, AND WHY THEY ARE NOT COMMITTED ANY MORE. The five
pictures are generated by `web/e2e/shots.spec.ts`, which drives the real client
in real Chromium and can only write PNG or JPEG -- Playwright has no WebP
encoder. So the PNG is an INTERMEDIATE: it is written to the gitignored
`web/help-shots/`, which is OUTSIDE `web/public/` because Vite copies that tree
into `dist/` wholesale and a PNG left there would ship beside the WebP cut from
it. This script is the step between the generator and what ships. Run them in
that order:

    cd web && npm run build && YOKOHAMA_WEB_SHOTS=1 npx playwright test shots.spec.ts
    python3 docs/tools/mkhelpart.py

WHY THE CUT IS WORTH A SCRIPT (M6.5b2, R-6.5b2.15 and spec §2.7). The five PNGs
are 4,210,470 B, which was 29% of the whole release and the second-largest thing
in it after the card art. As WebP at quality 90 they are 764,742 B, an 81.8%
cut, and a release that a service worker precaches WHOLE is a release where
every megabyte is paid by every visitor on every version. Committed for the same
reason `mkcardart.py`'s output is: a container that had to re-cut at build time
would need Python, Pillow and a browser, and these are needed at RUNTIME.

THE QUALITY WAS CHOSEN BY LOOKING, not by a rule of thumb. These are
screenshots of a dark instrument whose smallest printed text is 8.5px, so the
usual "85 is plenty for photographs" does not transfer -- chroma subsampling on
coloured text over a dark ground is exactly where WebP shows first. Measured on
the committed five at 1710x869, total bytes and the largest single file:

    q70  422,424 B   (95,242 max)
    q80  519,748 B  (116,944 max)
    q85  620,580 B  (141,078 max)
    q90  764,742 B  (174,782 max)     <- shipped
    q95  1,097,844 B (246,612 max)
    lossless 2,921,096 B

At 1:1 against the source PNG, q90 was indistinguishable on the two hardest
regions: the explanation chart's feature rows (11px mono with coloured
arithmetic beside it) and the pyramid's `A00`/`A01` id badges and printed power
ladders (8.5px over card art). q95 buys nothing visible and costs 43% more.

`--check` RE-ENCODES and compares bytes, so it answers "would this script,
running here, produce what is committed" and not "is the committed picture
right". A Pillow or libwebp bump can therefore report `DRIFTED` for pictures
nobody touched; that is a re-cut to take deliberately, not a defect to chase.

WHAT THIS DOES NOT PROVE. That the pictures are still the pictures the words
beside them describe. `web/src/Help.tsx` gives each shot an `alt` and a
`caption`, two of them are in `README.md`, and the server draws the game's seed
-- so every regeneration photographs a DIFFERENT game. Re-cutting is mechanical;
checking that the caption still describes what is in frame is not, and
`shots.spec.ts`'s own header is where that warning is written at length.

REQUIREMENTS: Pillow. Nothing in the workspace's Rust build or test path touches
it.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

try:
    from PIL import Image
except ImportError:  # pragma: no cover - a tooling problem, not a code path
    sys.exit("this script needs Pillow:  python3 -m pip install pillow")

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHOTS = ROOT / "web" / "help-shots"
HELP = ROOT / "web" / "public" / "help"

# See the header: chosen by comparing at 1:1, not by convention. `method=6` is
# Pillow's slowest and smallest encoder setting; these are five images cut once.
QUALITY = 90
METHOD = 6


def encode(png: pathlib.Path) -> bytes:
    """The WebP bytes for one screenshot.

    `convert("RGB")` is deliberate and not a formality: a Playwright screenshot
    is RGBA with a fully opaque alpha channel, and encoding that alpha costs
    bytes for a channel no help picture uses.
    """
    import io

    buf = io.BytesIO()
    with Image.open(png) as im:
        im.convert("RGB").save(buf, "WEBP", quality=QUALITY, method=METHOD)
    return buf.getvalue()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--check",
        action="store_true",
        help="compare against what is committed, write nothing, exit 1 on drift",
    )
    args = ap.parse_args()

    pngs = sorted(SHOTS.glob("*.png"))
    if not pngs:
        # The PNGs are gitignored intermediates, so a fresh clone has none. That
        # is not a crash to read backwards out of a Pillow error: say what is
        # missing and the command that makes it.
        sys.exit(
            f"no PNGs under {SHOTS.relative_to(ROOT)} — nothing to cut.\n"
            "  Generate them first:\n"
            "    cd web && npm run build && "
            "YOKOHAMA_WEB_SHOTS=1 npx playwright test shots.spec.ts"
        )

    # The output directory is tracked, so a clone has it — but the INPUT side
    # refuses absence with a named command and the output side should take the
    # same care rather than raise a `FileNotFoundError` from a write.
    HELP.mkdir(parents=True, exist_ok=True)

    drift = 0
    before = after = 0
    for png in pngs:
        webp = HELP / f"{png.stem}.webp"
        data = encode(png)
        before += png.stat().st_size
        after += len(data)
        if args.check:
            have = webp.read_bytes() if webp.exists() else b""
            state = "same" if have == data else "DRIFTED"
            drift += state == "DRIFTED"
            print(f"{state:8} {webp.relative_to(ROOT)}  {len(data)} B")
            continue
        webp.write_bytes(data)
        print(
            f"{webp.relative_to(ROOT)}  {png.stat().st_size} -> {len(data)} B"
            f"  (-{(1 - len(data) / png.stat().st_size) * 100:.1f}%)"
        )

    verb = "would be" if args.check else "are"
    print(
        f"{len(pngs)} pictures: {before} B of PNG {verb} {after} B of WebP "
        f"at quality {QUALITY} (-{(1 - after / before) * 100:.1f}%)"
    )
    if drift:
        print(f"{drift} of {len(pngs)} differ from what is committed.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

/** Writes `files` (path from `root` → text; `null` removes it) under `root`. */
function lay(root, files) {
  for (const [path, text] of Object.entries(files)) {
    if (text === null) {
      rmSync(join(root, path), { force: true });
      continue;
    }
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
}

/**
 * A worker package that passes every check, inside a scratch repository —
 * its `web/dist` holding the release the assets were assembled from, and a
 * crate's source the module was built from, stamped in `gen/source.json` —
 * with `changes` (a path from the worker package, `../` for the repository;
 * text, or `null` to leave the file out) laid over it BEFORE the stamp is
 * taken, and `since` laid over it AFTER: what changed since the build.
 */
function worker(changes = {}, since = {}) {
  const repo = mkdtempSync(join(tmpdir(), "deploy-guard-"));
  dirs.push(repo);
  const root = join(repo, "worker");
  lay(root, {
    "gen/factory.js": RELEASE_FACTORY,
    "assets/index.html": INDEX,
    "assets/sw.js": SW,
    "assets/_headers": assembledHeaders(STATIC_HEADERS, HEADERS_JSON),
    "assets/404.html": NOT_FOUND_PAGE,
    "assets/build-values.json": STAMP(false),
    "static/_headers": STATIC_HEADERS,
    "wrangler.jsonc": PRODUCTION,
    "wrangler.open.jsonc": OPEN_FILE,
    "wrangler.gate.jsonc": GATE,
    "wrangler.test.jsonc": TEST_CONFIG,
    "wrangler.open.test.jsonc": OPEN_TEST_CONFIG,
    "../web/dist/sw.js": SW,
    "../web/dist/headers.json": HEADERS_JSON,
    "../crates/yokohama-worker/src/lib.rs": "// the module\n",
  });
  if (!Object.hasOwn(changes, "gen/source.json")) {
    lay(root, { "gen/source.json": `${JSON.stringify({ digest: sourceDigest(repo) })}\n` });
  }
  lay(root, changes);
  lay(root, since);
  return root;
}


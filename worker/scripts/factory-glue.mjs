// **The factory transform** (spec §2.2; the spike's reading, spec §0.3 row 4).
//
// wasm-bindgen's `--target web` glue keeps its state at MODULE scope — `let
// wasm`, the cached view of its memory, the finalization registry over its
// replies — and its `initSync` returns early once `wasm` is set. An isolate
// evaluates a module once, so every Durable Object in an isolate would share
// ONE instance of the module, and so one `Games`; and a trapped instance could
// never be replaced.
//
// So the WHOLE glue body is wrapped in one function, `createModule(compiled)`,
// and every call builds its own instance over its own copy of that state — so
// each object can own one instance, and each instance one `Games`.
//
// The transform is textual, and it REFUSES rather than guesses. An `export`
// that survives it, a function it expects and does not find, an exported
// function it does not know, or a top-level `import` (which cannot live inside
// a function body) stops the build — so a wasm-bindgen upgrade that changes the
// glue's shape fails here instead of shipping a shared instance.
//
// `node scripts/factory-glue.mjs` reads `gen/yokohama_worker.js`, writes
// `gen/factory.js`, and copies `scripts/factory.d.ts.template` beside it as
// `gen/factory.d.ts`; `scripts/build-module.mjs` runs it LAST — after
// wasm-bindgen and, in a release build, after the optimizer.

import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** Every export the module has (the plan's names table), in the order the
 *  factory returns them. `debug_trap` is not here: only a `--features debug`
 *  build has it, and the factory returns it when the glue defines it. */
export const EXPECTED = [
  "init",
  "dispatch",
  "create",
  "events",
  "identity",
  "load",
  "read",
  "set_clock",
  "house_copy",
  "put_copy",
  "remove_copy",
  "house_frame",
  "restore_picker",
  "receipt",
  "stamp_archive",
  "expire",
  "share_prefix",
  "set_share",
];

/** The glue's own closing line, which the factory's single export replaces. */
const EXPORT_LIST = /^export \{ initSync, __wbg_init as default \};[ \t]*$/m;

/** The glue's first line points a reader at ITS declarations; the factory's
 *  are `factory.d.ts`, so the line would be false in `factory.js`. */
const SELF_TYPES = /^\/\*\s*@ts-self-types=.*\*\/[ \t]*\n?/m;

/** `factory.js` from the glue's text. Throws, naming what it found, when the
 *  glue is not the shape this transform knows. */
export function factoryGlue(source) {
  // `import.meta` and a dynamic `import(…)` are expressions, and legal inside
  // a function; an `import` STATEMENT is not.
  const imported = /^[ \t]*import\b(?![ \t]*[.(]).*$/m.exec(source);
  if (imported) {
    throw new Error(
      `factory-glue: the glue has a top-level import (${JSON.stringify(imported[0].trim())}), ` +
        "which cannot live inside the factory's function body",
    );
  }

  const exported = [...source.matchAll(/^export function (\w+)\(/gm)].map((m) => m[1]);
  const unknown = exported.filter((name) => !EXPECTED.includes(name) && name !== "debug_trap");
  if (unknown.length > 0) {
    throw new Error(
      `factory-glue: the glue exports ${unknown.join(", ")}, which the factory does not return — ` +
        "add each to EXPECTED and to factory.d.ts.template, or the shell cannot reach it",
    );
  }

  const body = source
    .replace(SELF_TYPES, "")
    .replace(EXPORT_LIST, "")
    .replace(/^export (class|function) /gm, "$1 ");

  const survivor = /^[ \t]*export\b.*$/m.exec(body);
  if (survivor) {
    throw new Error(
      `factory-glue: an export survived the transform (${JSON.stringify(survivor[0].trim())}) — ` +
        "the glue's shape changed, and an export inside a function body does not parse",
    );
  }

  const missing = [...EXPECTED, "initSync"].filter((name) => !new RegExp(`^function ${name}\\(`, "m").test(body));
  if (missing.length > 0) {
    throw new Error(
      `factory-glue: the glue has no function ${missing.join(", ")} — ` +
        "a module without every expected export is not the one the shell was written for",
    );
  }

  return (
    "// GENERATED by worker/scripts/factory-glue.mjs from gen/yokohama_worker.js — do not edit, and do not commit.\n" +
    "// Every call builds a NEW instance of the module over its own state (spec §2.2).\n" +
    "export function createModule(compiled) {\n" +
    body.trimEnd() +
    "\n\ninitSync({ module: compiled });\n" +
    `return { ${EXPECTED.join(", ")}, debug_trap: typeof debug_trap === "function" ? debug_trap : undefined };\n` +
    "}\n"
  );
}

/** Writes `factory.js` and `factory.d.ts` beside the glue in `gen`, and
 *  answers a line saying which module it wrapped. */
export function writeFactory(gen) {
  const source = readFileSync(join(gen, "yokohama_worker.js"), "utf8");
  writeFileSync(join(gen, "factory.js"), factoryGlue(source));
  copyFileSync(fileURLToPath(new URL("./factory.d.ts.template", import.meta.url)), join(gen, "factory.d.ts"));
  const debug = /^export function debug_trap\(/m.test(source);
  return (
    `factory-glue: gen/factory.js — ${EXPECTED.length} exports` +
    (debug ? " and debug_trap (a DEBUG module)" : " (a release module: no debug_trap)") +
    "; gen/factory.d.ts"
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    console.log(writeFactory(fileURLToPath(new URL("../gen/", import.meta.url))));
  } catch (e) {
    console.error(e instanceof Error ? e.message : String(e));
    process.exit(1);
  }
}

// **What the pool reads that is not the module** — the `pretest` and
// `pretypecheck` hook. All three outputs are gitignored and rebuilt on every
// run.
//
// 1. `.test-assets/`, the directory `wrangler.test.jsonc`'s `assets` block
//    serves: a one-line `index.html`, and a COPY of the real art manifest
//    under `art/`, so a cell of the Worker's `/api/art` can compare its answer
//    with the manifest the release ships.
//
// 2. `test/fixtures.gen.ts`: every file under `test/fixtures/` as a string
//    constant — `owed-pump.table.json` is `OWED_PUMP_TABLE_JSON`. Those are
//    Rust-made records and table documents that carry seeds above 2^53, and a
//    JSON import would PARSE them, rounding every such seed; as text they
//    reach the module byte for byte, and nothing in the shell parses a record
//    (the plan's Global Constraints). The pool's cells import this file, so
//    `typecheck` needs it as much as `test` does: CI type-checks a clean
//    checkout before any test has run.
//
//    It also carries the real art manifest's text as `ART_MANIFEST_JSON`, read
//    from `crates/yokohama-web/assets/art/` itself, so the Worker's `/api/art`
//    cell compares its answer with that file rather than with the copy the
//    pool's asset layer serves.
//
// 3. `test/corpus.gen.ts`: what the pool's corpus replay reads (spec §5.3) —
//    the committed corpus, every `web/src/wire/*.json` by its name less
//    `.json`, and the walk's two request scripts, `walk.json` and
//    `walk-host.json`, each as its TEXT. The replay derives its third column
//    from this listing exactly as the node replay derives its own from
//    `readdirSync`, and it parses each file itself, as the node replay does.
//    A file of its own, imported by the replay, its driver, and the Worker's
//    `/api/art` cell, which compares its answer with the committed
//    `art_manifest.json`.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const worker = fileURLToPath(new URL("..", import.meta.url));
const manifest = join(worker, "..", "crates", "yokohama-web", "assets", "art", "manifest.json");

const assets = join(worker, ".test-assets");
rmSync(assets, { recursive: true, force: true });
mkdirSync(join(assets, "art"), { recursive: true });
writeFileSync(join(assets, "index.html"), "<!doctype html><title>the pool's index.html</title>\n");
copyFileSync(manifest, join(assets, "art", "manifest.json"));

const fixtures = join(worker, "test", "fixtures");
const files = readdirSync(fixtures)
  .filter((f) => !f.startsWith(".") && statSync(join(fixtures, f)).isFile())
  .sort();
if (files.length === 0) {
  console.error(`test-assets: ${fixtures} holds no fixture — the committed ones are missing from this checkout.`);
  process.exit(1);
}

/** @type {Map<string, string>} constant name → file */
const names = new Map();
const lines = [];
for (const file of files) {
  const name = file.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();
  if (!/^[A-Z_][A-Z0-9_]*$/.test(name)) {
    console.error(`test-assets: ${file} does not name a constant (${name}); rename the fixture.`);
    process.exit(1);
  }
  if (names.has(name)) {
    console.error(`test-assets: ${names.get(name)} and ${file} would both be ${name}; rename one.`);
    process.exit(1);
  }
  names.set(name, file);
  lines.push(`/** \`test/fixtures/${file}\`, as its text. */`);
  lines.push(`export const ${name} = ${JSON.stringify(readFileSync(join(fixtures, file), "utf8"))};`);
}

// The art manifest, under a name no fixture may take.
const MANIFEST_NAME = "ART_MANIFEST_JSON";
if (names.has(MANIFEST_NAME)) {
  console.error(`test-assets: ${names.get(MANIFEST_NAME)} would be ${MANIFEST_NAME}, which the art manifest holds; rename it.`);
  process.exit(1);
}
names.set(MANIFEST_NAME, "crates/yokohama-web/assets/art/manifest.json");
lines.push("/** `crates/yokohama-web/assets/art/manifest.json`, as its text: what `/api/art` answers, by value. */");
lines.push(`export const ${MANIFEST_NAME} = ${JSON.stringify(readFileSync(manifest, "utf8"))};`);

writeFileSync(
  join(worker, "test", "fixtures.gen.ts"),
  "// GENERATED by worker/scripts/test-assets.mjs — do not edit, and do not commit.\n" +
    "// Every file under test/fixtures/, and the art manifest, as a string: never parsed, so a seed above 2^53\n" +
    "// keeps its digits.\n" +
    lines.join("\n") +
    "\n",
);

const web = join(worker, "..", "web", "src");
const wire = join(web, "wire");
const payloads = readdirSync(wire)
  .filter((f) => f.endsWith(".json"))
  .sort();
if (payloads.length === 0) {
  console.error(`test-assets: ${wire} holds no committed payload — the corpus is missing from this checkout.`);
  process.exit(1);
}
const script = (name) => JSON.stringify(readFileSync(join(web, "wire-script", name), "utf8"));
writeFileSync(
  join(worker, "test", "corpus.gen.ts"),
  "// GENERATED by worker/scripts/test-assets.mjs — do not edit, and do not commit.\n" +
    "// The committed corpus (web/src/wire/*.json) and the walk's two request scripts, as TEXT.\n" +
    "/** `web/src/wire-script/walk.json`, as its text. */\n" +
    `export const WALK_JSON = ${script("walk.json")};\n` +
    "/** `web/src/wire-script/walk-host.json`, as its text. */\n" +
    `export const WALK_HOST_JSON = ${script("walk-host.json")};\n` +
    "/** Every `web/src/wire/*.json`, by its name less `.json`, as its text. */\n" +
    "export const WIRE: Readonly<Record<string, string>> = {\n" +
    payloads.map((f) => `  ${JSON.stringify(f.slice(0, -".json".length))}: ${JSON.stringify(readFileSync(join(wire, f), "utf8"))},\n`).join("") +
    "};\n",
);

console.log(
  `test-assets: .test-assets/ (index.html, art/manifest.json); ` +
    `test/fixtures.gen.ts (${[...names.keys()].join(", ")}); ` +
    `test/corpus.gen.ts (WALK_JSON, WALK_HOST_JSON, WIRE: ${payloads.length} payloads)`,
);

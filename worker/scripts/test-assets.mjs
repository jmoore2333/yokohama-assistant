// **What the pool reads that is not the module** — the `pretest` and
// `pretypecheck` hook. Both outputs are gitignored and rebuilt on every run.
//
// 1. `.test-assets/`, the directory `wrangler.test.jsonc`'s `assets` block
//    serves: a one-line `index.html`, and a COPY of the real art manifest
//    under `art/`, so a cell of the Worker's `/api/art` can compare its answer
//    with the manifest the release ships.
//
// 2. `test/fixtures.gen.ts`: every file under `test/fixtures/` as a string
//    constant — `owed-pump.table.json` is `OWED_PUMP_TABLE_JSON`. Those are
//    Rust-made records and table documents that carry seeds above 2^53, and a
//    JSON import would PARSE them, rounding every such seed; as text they
//    reach the module byte for byte, and nothing in the shell parses a record
//    (the plan's Global Constraints). The pool's cells import this file, so
//    `typecheck` needs it as much as `test` does: CI type-checks a clean
//    checkout before any test has run.

import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const worker = fileURLToPath(new URL("..", import.meta.url));
const manifest = join(worker, "..", "crates", "yokohama-web", "assets", "art", "manifest.json");

const assets = join(worker, ".test-assets");
rmSync(assets, { recursive: true, force: true });
mkdirSync(join(assets, "art"), { recursive: true });
writeFileSync(join(assets, "index.html"), "<!doctype html><title>the pool's index.html</title>\n");
copyFileSync(manifest, join(assets, "art", "manifest.json"));

const fixtures = join(worker, "test", "fixtures");
const files = readdirSync(fixtures)
  .filter((f) => !f.startsWith(".") && statSync(join(fixtures, f)).isFile())
  .sort();
if (files.length === 0) {
  console.error(`test-assets: ${fixtures} holds no fixture — the committed ones are missing from this checkout.`);
  process.exit(1);
}

/** @type {Map<string, string>} constant name → file */
const names = new Map();
const lines = [];
for (const file of files) {
  const name = file.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();
  if (!/^[A-Z_][A-Z0-9_]*$/.test(name)) {
    console.error(`test-assets: ${file} does not name a constant (${name}); rename the fixture.`);
    process.exit(1);
  }
  if (names.has(name)) {
    console.error(`test-assets: ${names.get(name)} and ${file} would both be ${name}; rename one.`);
    process.exit(1);
  }
  names.set(name, file);
  lines.push(`/** \`test/fixtures/${file}\`, as its text. */`);
  lines.push(`export const ${name} = ${JSON.stringify(readFileSync(join(fixtures, file), "utf8"))};`);
}

writeFileSync(
  join(worker, "test", "fixtures.gen.ts"),
  "// GENERATED by worker/scripts/test-assets.mjs — do not edit, and do not commit.\n" +
    "// Every file under test/fixtures/ as a string: never parsed, so a seed above 2^53 keeps its digits.\n" +
    lines.join("\n") +
    "\n",
);

console.log(
  `test-assets: .test-assets/ (index.html, art/manifest.json); ` +
    `test/fixtures.gen.ts (${[...names.keys()].join(", ")})`,
);
